export function getFeedback(
  lang: Language,
  tone: Tone,
  status: Status | 'added',
) {
  if (tone === 'off') return '';
  const key =
    status === 'added' ||
    status === 'applied' ||
    status === 'offer' ||
    status === 'rejectedBefore' ||
    status === 'rejectedAfter' ||
    status === 'withdrawn'
      ? status
      : 'interview';
  return feedbackMessages[lang][tone][key];
}
