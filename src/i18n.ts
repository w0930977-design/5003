export const LocaleContext = createContext<Language>('zh');
export function useI18n() {
  const lang = useContext(LocaleContext);
  return {
    lang,
    t: (key: TranslationKey) => dictionaries[lang][key],
    statusLabel: (status: Status) => statusLabels[lang][status],
    date: (value: string) =>
      value
        ? new Date(`${value.slice(0, 10)}T12:00:00`).toLocaleDateString(
            lang === 'zh' ? 'zh-CN' : 'en-GB',
            { month: 'short', day: 'numeric', year: 'numeric' },
          )
        : dictionaries[lang].dateNone,
  };
}

